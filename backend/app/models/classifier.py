class VehicleMakeModelClassifier(nn.Module):
    """
    Deep Convolutional Network for vehicle fine-grained make and model classification.
    Can use ResNet-50 / EfficientNet backbone.
    """
    def __init__(self, num_classes: int = len(STANFORD_CARS_CLASSES)):
        super().__init__()
        try:
            import torchvision.models as models
            # Load pretrained ResNet50 backbone
            self.backbone = models.resnet50(weights=models.ResNet50_Weights.DEFAULT)
            in_features = self.backbone.fc.in_features
            self.backbone.fc = nn.Sequential(
                nn.Dropout(0.3),
                nn.Linear(in_features, 512),
                nn.ReLU(inplace=True),
                nn.Dropout(0.2),
                nn.Linear(512, num_classes)
            )
        except Exception:
            # Fallback simple architecture if torchvision weights not cached
            self.backbone = nn.Sequential(
                nn.Conv2d(3, 32, kernel_size=3, padding=1),
                nn.ReLU(),
                nn.AdaptiveAvgPool2d((1, 1)),
                nn.Flatten(),
                nn.Linear(32, num_classes)
            )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.backbone(x)
